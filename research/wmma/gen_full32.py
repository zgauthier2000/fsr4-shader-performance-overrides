# All-WMMA version of FSR 4.1.1's pass 1 (3x3 16 -> 16, 1x1 16 -> 32, 1x1 32 -> 16, residual), for 32-wide waves.
# Weight extraction as in gen_hybrid.py. Bias offsets are pass 1's.
# usage: gen_full32.py <pass.spvasm> > out.comp
import os
import re
import subprocess
import sys

src = sys.argv[1]
wave = int(sys.argv[2]) if len(sys.argv) > 2 else 32
pp = subprocess.run([sys.executable, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pp.py'), src],
                    capture_output=True, text=True, check=True).stdout.split('\n')

def die(msg):
    sys.exit('gen_pass1: ' + msg)

def num(tok):
    return int(tok, 0) & 0xffffffff

# Walk the pseudo-code: constant stores into local arrays, and the loops that consume them.
arrays = {}          # 'L47' -> {index: value}
alias = {}           # '%270' -> ('%268', 0): index = phi + offset
loops = []           # (dest array, dest offset, weight array, [16 words], [input ids])
block = []
for line in pp:
    m = re.match(r'\d+: (L\d+)\[(\d+)\] = (0x[0-9a-f]+|-?\d+)$', line)
    if m:
        arrays.setdefault(m[1], {})[int(m[2])] = num(m[3])
    if re.match(r'\d+: %\w+:$', line):
        block = []
    block.append(line)
    if 'LoopMerge' in line:
        dots = [re.search(r'sdot\((\S+), (\S+)\)', x) for x in block]
        dots = [d for d in dots if d]
        dest = [re.match(r'\d+: (L\d+)\[(%\w+)\] = ', x) for x in block]
        dest = [d for d in dest if d]
        if len(dots) != 4 or not dest:
            die('unexpected loop shape')
        off = None
        for x in block:
            a = re.match(r'\d+: ' + re.escape(dest[0][2]) + r' = %\w+ \+ (\d+)$', x)
            if a:
                off = int(a[1])
        if off is None:
            die('no destination offset')
        loops.append({'dst': dest[0][1], 'off': off, 'ins': [d[1] for d in dots], 'at': len(loops)})
        loops[-1]['pending'] = True
    # the continue block names the weight array
    m = re.match(r'\d+: %\w+ = (L\d+)\[%\w+\]$', line)
    if m and loops and loops[-1].get('pending') and m[1] != loops[-1]['dst']:
        loops[-1]['w'] = [arrays[m[1]][k] for k in range(16)]
        loops[-1]['pending'] = False

if len(loops) != 52:
    die(f'expected 52 loops, found {len(loops)}')
conv1, conv2, conv3 = loops[:36], loops[36:44], loops[44:]
text = '\n'.join(pp)
for needle in ('+ 3456', '+ 4096', '+ 4736', '30752 *', '+ 33273664', '>u 1919', '>u 1079', 'cbv[2]', '>>s 7', '>>s 8',
               '*f 0.015625', '*f 0.000244140625', '*f 64'):
    if needle not in text:
        die(f'pass does not match the expected structure: no "{needle}"')
bias = [int(x) for x in re.findall(r'= %\w+ \+ (3456|4096|4736|\d{4})$', text, re.M)]

# Matrices: A[oc][ic] row major, 4 words per output channel.  Order: conv1 taps 0..8, conv2 a/b, conv3 a/b.
mats = [[0] * 64 for _ in range(13)]
seen = set()
for i, l in enumerate(conv1):
    g, tap = i // 9, i % 9
    if l['off'] != 4 * g:
        die('conv1 loop order')
    for oc in range(4):
        for k in range(4):
            mats[tap][(4 * g + oc) * 4 + k] = l['w'][4 * oc + k]
for i, l in enumerate(conv2):
    if l['off'] != 4 * i:
        die('conv2 loop order')
    for oc in range(4):
        for k in range(4):
            mats[9 + i // 4][((4 * i + oc) % 16) * 4 + k] = l['w'][4 * oc + k]
first_half = conv3[0]['ins']
for i, l in enumerate(conv3):
    g, half = i // 2, 0 if l['ins'] == first_half else 1
    if l['off'] != 4 * g or half != i % 2:
        die('conv3 loop order')
    for oc in range(4):
        for k in range(4):
            mats[11 + half][(4 * g + oc) * 4 + k] = l['w'][4 * oc + k]


cmat = lambda ms: ',\n    '.join(', '.join(f'0x{v:08x}u' for v in m[i:i + 8]) for m in ms for i in range(0, 64, 8))



# Row permutation: accumulator row r is held by lanes g = r & 1 as element r >> 1. Give row r output channel
# perm(r) = 8 (r & 1) + (r >> 1), so lane g holds channels 8g .. 8g + 7 of its pixel, in order (two packed words).
perm = [8 * (r & 1) + (r >> 1) for r in range(16)]
def rowperm(m):
    return [m[perm[r] * 4 + k] for r in range(16) for k in range(4)]
pm = [rowperm(m) for m in mats]          # every matrix's rows: they are output channels
B1, B2, B3 = 864, 1024, 1184
T = f"""#version 460
// Generated by gen_full32.py (v2) from {src.rsplit('/', 1)[-1]}: all three convolutions of a residual-block pass by
// WMMA, for 32-wide waves (two waves per workgroup of 64: RADV_PERFTEST=cswave32, or WaveSize(32) in DXIL).
// Wave w owns pixels x0 + 32w + 16t + p (tile t = 0, 1). The rows of every weight matrix are permuted so that
// invocation (g = lane / 16, p = lane % 16) receives channels 8g .. 8g + 7 of pixel p: it rounds them, packs two words,
// and writes them to shared memory, where they form column p of the next layer's B matrix in channel order.
#extension GL_KHR_cooperative_matrix : require
#extension GL_KHR_memory_scope_semantics : require
#extension GL_KHR_shader_subgroup_basic : require
#extension GL_EXT_shader_explicit_arithmetic_types : require
#extension GL_EXT_control_flow_attributes : require
#extension GL_EXT_nonuniform_qualifier : require
#extension GL_EXT_buffer_reference : require
#extension GL_EXT_buffer_reference_uvec2 : require
layout(local_size_x = 64) in;
layout(buffer_reference, std430, buffer_reference_align = 16) readonly buffer Sizes {{ uvec4 v[4096]; }};
layout(push_constant) uniform Root {{ uvec2 cbv; uint uav; uint srv; }} reg;
layout(set = 2, binding = 0) buffer Tensor {{ uint d[]; }} heap[];
layout(set = 2, binding = 0) readonly buffer Weights {{ uint d[]; }} wheap[];

#define ACC coopmat<int32_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>
#define MATA coopmat<int8_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA>
#define MATB coopmat<int8_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseB>

const uint WALL[13 * 64] = uint[](
    {cmat(pm)});
shared uint s_w[13 * 64];
shared uint s_b[2 * 4 * 64];            // [wave][slot][pixel * 4 + word]
#define SB(w, s) (((w) * 4u + (s)) * 64u)

uint pk(int q[8], uint h) {{ return uint(q[4u*h] & 0xff) | uint(q[4u*h+1u] & 0xff) << 8 | uint(q[4u*h+2u] & 0xff) << 16 | uint(q[4u*h+3u] & 0xff) << 24; }}

void main() {{
    const uint lane = gl_LocalInvocationIndex & 31u, p = lane & 15u, g = lane >> 4, wv = gl_LocalInvocationIndex >> 5;
    const uint y = gl_WorkGroupID.y, x0 = gl_WorkGroupID.x * 64u + wv * 32u;
    const uint tensor = reg.uav + 11u, wbuf = reg.srv + 18u;
    for (uint k = gl_LocalInvocationIndex; k < 13u * 64u; k += 64u)
        s_w[k] = WALL[k];
    const uvec2 size = Sizes(reg.cbv).v[2].xy;
    barrier();
    MATA a[13];
    [[unroll]] for (uint m = 0u; m < 13u; m++)
        coopMatLoad(a[m], s_w, m * 64u, 4u, gl_CooperativeMatrixLayoutRowMajor);

    [[unroll]] for (uint t = 0u; t < 2u; t++) {{
        // layer 1: 3x3, 16 -> 16
        ACC acc = ACC(0);
        [[unroll]] for (uint tap = 0u; tap < 9u; tap++) {{
            MATB b;
            coopMatLoad(b, heap[tensor].d, ((y + tap / 3u) * 1922u + x0 + t * 16u + tap % 3u) * 4u, 4u, gl_CooperativeMatrixLayoutColumnMajor);
            acc = coopMatMulAdd(a[tap], b, acc);
        }}
        int q[8];
        [[unroll]] for (uint i = 0u; i < 8u; i++) {{
            const int v = acc[i] + int(wheap[wbuf].d[{B1}u + 8u * g + i]);
            q[i] = clamp((v + 63 + ((v >> 7) & 1)) >> 7, -128, 127);
        }}
        s_b[SB(wv, 0u) + p * 4u + 2u * g] = pk(q, 0u); s_b[SB(wv, 0u) + p * 4u + 2u * g + 1u] = pk(q, 1u);
        subgroupBarrier();
        MATB b1;
        coopMatLoad(b1, s_b, SB(wv, 0u), 4u, gl_CooperativeMatrixLayoutColumnMajor);
        // layer 2: 1x1, 16 -> 32, ReLU
        [[unroll]] for (uint rb = 0u; rb < 2u; rb++) {{
            ACC c2 = coopMatMulAdd(a[9u + rb], b1, ACC(0));
            [[unroll]] for (uint i = 0u; i < 8u; i++) {{
                const int v = max(c2[i] + int(wheap[wbuf].d[{B2}u + 16u * rb + 8u * g + i]), 0);
                q[i] = min((v + 127 + ((v >> 8) & 1)) >> 8, 127);
            }}
            s_b[SB(wv, 1u + rb) + p * 4u + 2u * g] = pk(q, 0u); s_b[SB(wv, 1u + rb) + p * 4u + 2u * g + 1u] = pk(q, 1u);
        }}
        subgroupBarrier();
        // layer 3: 1x1, 32 -> 16
        ACC c3 = ACC(0);
        [[unroll]] for (uint kb = 0u; kb < 2u; kb++) {{
            MATB b2;
            coopMatLoad(b2, s_b, SB(wv, 1u + kb), 4u, gl_CooperativeMatrixLayoutColumnMajor);
            c3 = coopMatMulAdd(a[11u + kb], b2, c3);
        }}
        // residual and store: channels 8g .. 8g + 7 of pixel p of tile t
        const uint x = x0 + t * 16u + p;
        const uint center = ((y + 1u) * 1922u + x + 1u) * 4u + 2u * g;
        const uint in0 = heap[tensor].d[center], in1 = heap[tensor].d[center + 1u];
        [[unroll]] for (uint i = 0u; i < 8u; i++) {{
            const int tt = c3[i] + int(wheap[wbuf].d[{B3}u + 8u * g + i]);
            const int v = int((i < 4u ? in0 : in1) << (24u - 8u * (i & 3u))) >> 24;
            const float f = (float(v) * 0.015625 + float(tt) * 0.000244140625) * 64.0;
            q[i] = clamp(int(int16_t(roundEven(f))), -128, 127);
        }}
        if (x < size.x && y < size.y && x <= 1919u && y <= 1079u) {{
            heap[tensor].d[(33273664u >> 2) + center] = pk(q, 0u);
            heap[tensor].d[(33273664u >> 2) + center + 1u] = pk(q, 1u);
        }}
        subgroupBarrier();
    }}
}}"""
print(T)
