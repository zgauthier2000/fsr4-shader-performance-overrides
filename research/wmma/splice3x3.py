#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0-or-later
# Hybrid by splicing: AMD's pass, decompiled to GLSL (spirv-cross), with its first layer (3x3, 16 -> 16, weights as
# constants: passes 1, 2, 4, 5, 10, 12) computed by WMMA at the top of main(). Each lane gets the 16 int32 sums of its own
# pixel by a lane exchange; after AMD's 36 loops of that layer, its accumulators are overwritten with bias + those sums,
# so the loops are dead and the compiler drops them. Everything after that layer is AMD's code.
# usage: splice3x3.py <pass.comp (spirv-cross)> <wave 32|64> [ntaps] > hybrid.comp
#   wave 32: for running with RADV_PERFTEST=cswave32 (two waves per workgroup of 64)
import re, sys

src = open(sys.argv[1]).read()
wave = int(sys.argv[2])
assert wave in (32, 64)

# --- the first 36 loops: weight array, destination array and offset, in source order
body = src[src.index('void main()'):]
loops = []
for m in re.finditer(r'for \(;;\)\s*\{', body):
    seg = body[m.end():m.end() + 1500]
    st = re.search(r'(_\d+)\[([^\]]+)\] = [^;]*spvSDot[^;]*;', seg)
    w = re.search(r'= (_\d+)\[3u \+ \(_\d+ \* 4u\)\];', seg)
    if not st or not w or len(re.findall(r'spvSDot', st[0])) != 4:
        break
    idx = st[2]
    o = re.match(r'_\d+ \+ (\d+)u$', idx)
    if not o:
        t = re.search(r'uint ' + re.escape(idx) + r' = _\d+ \+ (\d+)u;', seg)
        o = t
    # the weight words this loop starts with: the latest assignment of each index before the loop
    pre = body[:m.start()]
    wv = {}
    for a in re.finditer(re.escape(w[1]) + r'\[(\d+)u\] = (\d+)u;', pre):
        wv[int(a[1])] = int(a[2])
    loops.append(dict(start=m.start(), dst=st[1], off=int(o[1]), warr=w[1], w=[wv[k] for k in range(16)]))
    if len(loops) == 36:
        break
if len(loops) != 36:
    sys.exit(f'splice3x3: found {len(loops)} leading 4-dot loops, expected 36')
acc = loops[0]['dst']
if any(l['dst'] != acc for l in loops):
    sys.exit('splice3x3: loops write different arrays')

# weights: A[tap][oc][ic] as 64 words per tap; loop i = group i // 9 (output channels 4g..4g+3), tap i % 9
mats = [[0] * 64 for _ in range(9)]
for i, l in enumerate(loops):
    g, tap = i // 9, i % 9
    if l['off'] != 4 * g:
        sys.exit('splice3x3: loop order is not group-major')
    w = l['w']
    for oc in range(4):
        for k in range(4):
            mats[tap][(4 * g + oc) * 4 + k] = w[4 * oc + k]

# tensor addressing of the input: from the first tap load before loop 0, "(STRIDE * gid.y) + _x) [+ BASE]"
pre = body[:loops[0]['start']]
m = re.findall(r'\(\((\d+)u \* gl_GlobalInvocationID\.y\) \+ _\d+\) \+ (\d+)u;', pre) or \
    [(s, '0') for s in re.findall(r'\((\d+)u \* gl_GlobalInvocationID\.y\) \+ _\d+;', pre)]
stride, base = int(m[-1][0]), int(m[-1][1])
tb = re.search(r'registers\._m1 \+ (\d+)u', pre)[1]
tens = re.search(r'(_\d+)\[_\d+\]\._m0\[_\d+\], \1\[_\d+\]\._m0\[_\d+ \+ 1u\]', pre[pre.rindex('gl_GlobalInvocationID.y'):])[1]
ntaps = int(sys.argv[3]) if len(sys.argv) > 3 else 9

# --- header
hdr_ext = """#extension GL_KHR_cooperative_matrix : require
#extension GL_KHR_memory_scope_semantics : require
#extension GL_KHR_shader_subgroup_basic : require
#extension GL_KHR_shader_subgroup_shuffle : require
#extension GL_EXT_shader_explicit_arithmetic_types : require
#extension GL_EXT_control_flow_attributes : require
"""
out = src.replace('#version 450\n', '#version 460\n' + hdr_ext, 1)
consts = ',\n    '.join(', '.join(f'0x{v:08x}u' for v in mats[t][i:i + 8]) for t in range(9) for i in range(0, 64, 8))
glob = f"""
#define HACC coopmat<int32_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>
#define HMATA coopmat<int8_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA>
#define HMATB coopmat<int8_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseB>
const uint HW1[576] = uint[](
    {consts});
shared uint h_sw[576];
"""
out = out.replace('void main()\n{\n', glob + 'void main()\n{\n' + '__HYB_TOP__', 1)

nt = 64 // 16 if wave == 64 else 2       # tiles per wave
ne = 16 // (wave // 16)                   # accumulator elements per lane
top = f"""    // ---- hybrid: 3x3 layer by WMMA (generated by splice3x3.py, wave {wave}, {ntaps} taps)
    for (uint k = gl_LocalInvocationIndex; k < 576u; k += 64u)
        h_sw[k] = HW1[k];
    barrier();
    int h_sum[16];
    {{
        const uint lane = gl_SubgroupInvocationID, p = lane & 15u, g = lane >> 4;
        const uint y = gl_WorkGroupID.y, x0 = gl_WorkGroupID.x * 64u + gl_SubgroupID * {wave}u;
        HMATA ha[9];
        [[unroll]] for (uint m = 0u; m < 9u; m++)
            coopMatLoad(ha[m], h_sw, m * 64u, 4u, gl_CooperativeMatrixLayoutRowMajor);
        int hv[{nt}][{ne}];
        [[unroll]] for (uint t = 0u; t < {nt}u; t++) {{
            HACC hacc = HACC(0);
            [[unroll]] for (uint tap = 0u; tap < {ntaps}u; tap++) {{
                HMATB hb;
                coopMatLoad(hb, {tens}[registers._m1 + {tb}u]._m0, ({base}u + {stride}u * (y + tap / 3u) + (x0 + t * 16u + tap % 3u) * 16u) >> 2u, 4u, gl_CooperativeMatrixLayoutColumnMajor);
                hacc = coopMatMulAdd(ha[tap], hb, hacc);
            }}
            [[unroll]] for (uint i = 0u; i < {ne}u; i++) hv[t][i] = hacc[i];
        }}
"""
if wave == 64:
    # lane (g, p) holds channel g + 4i of pixel p of every tile; it finishes tile g
    top += """        [[unroll]] for (uint i = 0u; i < 4u; i++) {
            int own = hv[0][i];
            [[unroll]] for (uint t = 1u; t < 4u; t++) if (g == t) own = hv[t][i];
            h_sum[g + 4u * i] = own;
        }
        [[unroll]] for (uint d = 1u; d < 4u; d++)
            [[unroll]] for (uint i = 0u; i < 4u; i++) {
                int send = hv[0][i];
                [[unroll]] for (uint t = 1u; t < 4u; t++) if ((g ^ d) == t) send = hv[t][i];
                h_sum[(g ^ d) + 4u * i] = subgroupShuffleXor(send, 16u * d);
            }
    }
"""
else:
    # lane (g, p) holds channel g + 2i of pixel p of both tiles; it finishes tile g
    top += """        [[unroll]] for (uint i = 0u; i < 8u; i++) {
            const int own = g == 0u ? hv[0][i] : hv[1][i];
            const int send = g == 0u ? hv[1][i] : hv[0][i];
            h_sum[g + 2u * i] = own;
            h_sum[(g ^ 1u) + 2u * i] = subgroupShuffleXor(send, 16u);
        }
    }
"""
out = out.replace('__HYB_TOP__', top, 1)

# --- capture the biases before loop 0, overwrite the accumulators after loop 35
b = out.index('void main()')
starts = [m.start() + b for m in re.finditer(r'for \(;;\)\s*\{', out[b:])]
first, last = starts[0], starts[35]
# end of loop 35: matching brace
i = out.index('{', last); depth = 0
while True:
    if out[i] == '{': depth += 1
    elif out[i] == '}':
        depth -= 1
        if depth == 0: break
    i += 1
end = i + 1
ind = re.search(r'\n(\s*)for \(;;\)', out[first - 200:first + 10])[1]
cap = f'uint h_bias[16];\n{ind}[[unroll]] for (uint c = 0u; c < 16u; c++) h_bias[c] = {acc}[c];\n{ind}'
put = f'\n{ind}[[unroll]] for (uint c = 0u; c < 16u; c++) {acc}[c] = h_bias[c] + uint(h_sum[c]);'
out = out[:end] + put + out[end:]
out = out[:first] + cap + out[first:]
sys.stderr.write(f'splice3x3: acc {acc}, tensor {tens}[uav+{tb}], stride {stride}, base {base}, wave {wave}\n')
print(out)
