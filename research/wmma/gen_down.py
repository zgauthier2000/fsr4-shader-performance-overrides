# Full WMMA versions of passes 3 and 6 (2x2 stride-2 convolution, 4K output): one layer, so no handoff between layers.
#   pass 3: 16 -> 32 channels, level 1 -> 2; pass 6: 32 -> 64 channels, level 2 -> 3.
# A[tap][out block][in block] loads straight from the weight buffer (rows of KIN bytes per output channel); biases are
# consecutive words; rounding as AMD's: roundEven(sum * SCALE) through int16, clamped to int8. Input and output tensors
# are planes of 16 channels. Rows of A are permuted so that each invocation receives whole words of consecutive channels
# of its own pixel and stores them itself (wave 32: lane group g has channels 8g .. 8g + 7 of a block; wave 64: 4g ..).
# usage: gen_down.py 3|6 32|64 > out.comp      (32: run with a required subgroup size of 32)
import sys
P = {
    3: dict(kin=1, kout=2, istride=30752, ibase=0, iplane=0, wbase=8576, wtap=512, bias=2656, scale='0.0078125',
           obase=33273664, oplane=8342464, ostride=15392, w=960, h=540),
    6: dict(kin=2, kout=4, istride=15392, ibase=33273664, iplane=8342464, wbase=24576, wtap=2048, bias=8192, scale='0.00390625',
           obase=49958592, oplane=2097664, ostride=7712, w=480, h=270)}[int(sys.argv[1])]
wave = int(sys.argv[2])
nt, ne, gs = (2, 8, 2) if wave == 32 else (4, 4, 4)
kin, kout = P['kin'], P['kout']
rowb = 16 * kin                       # bytes of weights per output channel and tap
nm = 4 * kout * kin                   # A matrices
print(f"""#version 460
// Generated by gen_down.py {sys.argv[1]} {wave}
#extension GL_KHR_cooperative_matrix : require
#extension GL_KHR_memory_scope_semantics : require
#extension GL_EXT_shader_explicit_arithmetic_types : require
#extension GL_EXT_control_flow_attributes : require
#extension GL_EXT_nonuniform_qualifier : require
layout(local_size_x = 64) in;
layout(push_constant) uniform Root {{ uint uav; uint srv; }} reg;
layout(set = 2, binding = 0) buffer Tensor {{ uint d[]; }} heap[];
layout(set = 2, binding = 0) readonly buffer Weights {{ uint d[]; }} wheap[];
#define ACC coopmat<int32_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>
#define MATA coopmat<int8_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA>
#define MATB coopmat<int8_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseB>
shared uint s_w[{nm} * 64];
uint perm(uint r) {{ return {ne}u * (r % {gs}u) + r / {gs}u; }}

void main() {{
    const uint lane = gl_LocalInvocationIndex % {wave}u, p = lane & 15u, g = lane >> 4, wv = gl_LocalInvocationIndex / {wave}u;
    const uint y = gl_WorkGroupID.y, x0 = gl_WorkGroupID.x * 64u + wv * {wave}u;
    const uint tensor = reg.uav + 11u, wbuf = reg.srv + 18u;
    // s_w[((tap * {kout} + ob) * {kin} + ib) * 64 + r * 4 + k] = word k of input block ib of channel 16 ob + perm(r)
    for (uint i = gl_LocalInvocationIndex; i < {nm * 64}u; i += 64u) {{
        const uint m = i >> 6, r = (i >> 2) & 15u, k = i & 3u, ib = m % {kin}u, ob = (m / {kin}u) % {kout}u, tap = m / {kin * kout}u;
        s_w[i] = wheap[wbuf].d[({P['wbase']}u + {P['wtap']}u * tap + {rowb}u * (16u * ob + perm(r)) + 16u * ib) / 4u + k];
    }}
    barrier();
    MATA a[{nm}];
    [[unroll]] for (uint m = 0u; m < {nm}u; m++)
        coopMatLoad(a[m], s_w, m * 64u, 4u, gl_CooperativeMatrixLayoutRowMajor);
    [[unroll]] for (uint t = 0u; t < {nt}u; t++) {{
        MATB b[4][{kin}];
        [[unroll]] for (uint tap = 0u; tap < 4u; tap++)
            [[unroll]] for (uint ib = 0u; ib < {kin}u; ib++)
                coopMatLoad(b[tap][ib], heap[tensor].d, ({P['ibase']}u + {P['iplane']}u * ib + {P['istride']}u * (2u * y + 1u + tap / 2u) + (2u * (x0 + 16u * t) + 1u + tap % 2u) * 16u) >> 2, 8u, gl_CooperativeMatrixLayoutColumnMajor);
        const uint x = x0 + 16u * t + p;
        [[unroll]] for (uint ob = 0u; ob < {kout}u; ob++) {{
            ACC acc = ACC(0);
            [[unroll]] for (uint tap = 0u; tap < 4u; tap++)
                [[unroll]] for (uint ib = 0u; ib < {kin}u; ib++)
                    acc = coopMatMulAdd(a[(tap * {kout}u + ob) * {kin}u + ib], b[tap][ib], acc);
            uint w[{ne // 4}];
            [[unroll]] for (uint j = 0u; j < {ne // 4}u; j++) w[j] = 0u;
            [[unroll]] for (uint i = 0u; i < {ne}u; i++) {{
                const int v = acc[i] + int(wheap[wbuf].d[{P['bias']}u + 16u * ob + {ne}u * g + i]);
                const int q = clamp(int(int16_t(roundEven(float(v) * {P['scale']}))), -128, 127);
                w[i >> 2] |= uint(q & 0xff) << (8u * (i & 3u));
            }}
            const uint base = ({P['obase']}u + {P['oplane']}u * ob + {P['ostride']}u * (y + 1u) + (x + 1u) * 16u) >> 2;
            if (x < {P['w']}u && y < {P['h']}u)
                [[unroll]] for (uint j = 0u; j < {ne // 4}u; j++) heap[tensor].d[base + {ne // 4}u * g + j] = w[j];
        }}
    }}
}}""")
