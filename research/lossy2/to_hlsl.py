# to_hlsl.py: a generated lossy2 network pass (gen_lossy2.py's GLSL, written for vkd3d-proton) as HLSL for DXC, the Windows DLL's form:
# AMD's INT8 model passes use cbuffer CsTensorSizes (b0), ByteAddressBuffer InitializerBuffer (t18), RWByteAddressBuffer ScratchBuffer (u11);
# compute, 64x1x1 threads, native 16-bit types. The arithmetic is translated one to one (packed 4x8 dot products, round half to even, byte
# packing); any GLSL-only name left over stops the translation. convert(glsl, name) -> HLSL text. Copied from this project's student-network
# work (gen_hlsl.py) with the header comment changed.
import re, sys, os

TYPES = {'uvec2': 'uint2', 'uvec3': 'uint3', 'uvec4': 'uint4', 'ivec2': 'int2', 'ivec3': 'int3', 'ivec4': 'int4',
         'vec2': 'float2', 'vec3': 'float3', 'vec4': 'float4'}
HEAD = """// generated by to_hlsl.py from {src}: a lossy2 network pass (trained weights; see research/lossy2)
cbuffer CsTensorSizes : register(b0) {{ uint4 tensorSizes[17]; }};
ByteAddressBuffer InitializerBuffer : register(t18);
RWByteAddressBuffer ScratchBuffer : register(u11);

[numthreads(64, 1, 1)]
void main(uint3 gl_GlobalInvocationID : SV_DispatchThreadID, uint3 gl_WorkGroupID : SV_GroupID)
"""

def close(s, i, o='(', c=')'):
    """index of the bracket closing the one at s[i]"""
    d = 0
    for j in range(i, len(s)):
        if s[j] == o: d += 1
        elif s[j] == c:
            d -= 1
            if d == 0: return j
    raise ValueError(f'unbalanced {o}{c} at {i}')

def args(inner):
    """split a call's argument text at top-level commas"""
    out, d, st = [], 0, 0
    for j, ch in enumerate(inner):
        if ch in '([{': d += 1
        elif ch in ')]}': d -= 1
        elif ch == ',' and d == 0: out.append(inner[st:j].strip()); st = j + 1
    out.append(inner[st:].strip()); return out

def calls(s, name, fn):
    """replace every call name(...) (innermost first, by repeated passes) with fn(list of argument texts)"""
    pat = re.compile(r'(?<![A-Za-z0-9_])' + re.escape(name) + r'\(')
    while True:
        ms = list(pat.finditer(s))
        if not ms: return s
        for m in reversed(ms):          # last first: earlier indices stay valid
            a = m.end() - 1; b = close(s, a)
            s = s[:m.start()] + fn(args(s[a + 1:b])) + s[b + 1:]

def buffers(s):
    """the descriptor-heap buffer accesses -> ByteAddressBuffer loads and stores"""
    pat = re.compile(r'_(26|27|15|21)\[registers\._m1 \+ (11|18)u\]\._m0\[')
    while True:
        m = pat.search(s)
        if not m: return s
        arr, reg = m.group(1), m.group(2); a = m.end() - 1; b = close(s, a, '[', ']'); idx = s[a + 1:b]
        wide = arr in ('27', '21'); buf = 'ScratchBuffer' if reg == '11' else 'InitializerBuffer'
        assert (reg == '11') == (arr in ('26', '27')), m.group(0)
        byte = f'(({idx}) << {"4u" if wide else "2u"})'
        rest = s[b + 1:]; w = re.match(r'\s*=(?!=)', rest)
        if w:                                   # a store: buf[idx] = value;
            assert buf == 'ScratchBuffer'
            e = rest.index(';', w.end()); val = rest[w.end():e].strip()
            s = s[:m.start()] + f'{buf}.{"Store4" if wide else "Store"}({byte}, {val})' + rest[e:]
        else: s = s[:m.start()] + f'{buf}.{"Load4" if wide else "Load"}({byte})' + rest

def body(s):
    s = s.replace('PhysicalPointerUint4NonWriteCBVArray(registers._m0).value[', 'tensorSizes[')
    s = buffers(s)
    s = calls(s, 'spvSDot_uint_uint_uint', lambda a: (f'uint(dot4add_i8packed({a[0]}, {a[1]}, int({a[2]})))'))
    s = calls(s, 'unpack8', lambda a: f'unpack8__({a[0]})')            # mark, then the only form used: ivec4(i8vec4(unpack8(w)))
    s = calls(s, 'pack32', lambda a: f'pack32__({a[0]})')
    s = re.sub(r'ivec4\(i8vec4\(unpack8__\(([^()]*)\)\)\)', r'unpack_s8s32((int8_t4_packed)(\1))', s)
    assert 'unpack8__' not in s, 'gen_hlsl.py: unpack8 in another form than ivec4(i8vec4(unpack8(w)))'
    s = calls(s, 'pack32__', lambda a: f'(uint)pack_u8(uint4({re.sub(r"^(u8vec4|i8vec4)", "", a[0])}))')
    s = s.replace('roundEven(', 'round(')
    s = re.sub(r'(\b(?:uint|int))\[\]\(', r'\1_arr__(', s)               # GLSL array initializers uint[](...) -> {...}
    s = calls(s, 'uint_arr__', lambda a: '{' + ', '.join(a) + '}'); s = calls(s, 'int_arr__', lambda a: '{' + ', '.join(a) + '}')
    for g, h in TYPES.items():                                          # one argument: a cast (splat or conversion); more: a constructor
        s = calls(s, g, lambda a, h=h: f'(({h})({a[0]}))' if len(a) == 1 else f'{h}({", ".join(a)})')
        s = re.sub(r'(?<![A-Za-z0-9_])' + g + r'(?![A-Za-z0-9_])', h, s)   # declarations
    for bad in ('unpack8', 'pack32', 'u8vec4', 'i8vec4', 'uvec', 'ivec', 'spvSDot', 'registers', '_m0', 'roundEven', 'gl_LocalInvocationID',
                'barrier', 'shared', '[](' ):
        assert bad not in s.replace('gl_GlobalInvocationID', '').replace('gl_WorkGroupID', ''), f'gen_hlsl.py: left over: {bad}'
    return s

# LOAD4=1 (2026-10-19, Windows speed): the GLSL reads each 16-byte value as four 32-bit words, uint4(t[(ib + 0) >> 2], t[(ib + 4) >> 2], ...),
# which RADV merges into one 16-byte load; DXC keeps four (dxc -Fc of the kit's pass 7: 80 one-word loads; AMD's pass 7: 96 four-word loads). This
# folds each such group into one Load4 at the first word's byte address (ib is 16-byte aligned in gen_net's layout). Off by default: the DLLs
# built before stay reproducible.
ONE = r'ScratchBuffer\.Load\(\(\(\(([^()]+?) \+ (\d+)u\) >> 2u\) << 2u\)\)'
def wide_loads(s):
    pat = re.compile(r'uint4\(' + ', '.join([ONE] * 4) + r'\)'); n = 0
    def f(m):
        nonlocal n
        e = m.group(1); o = [int(m.group(2 * i + 2)) for i in range(4)]
        if any(m.group(2 * i + 1) != e for i in range(4)) or o != [o[0], o[0] + 4, o[0] + 8, o[0] + 12] or o[0] % 4: return m.group(0)
        n += 1; return f'ScratchBuffer.Load4(({e}) + {o[0]}u)'
    s = pat.sub(f, s)
    print(f'gen_hlsl.py LOAD4: {n} groups of four loads -> Load4, {len(re.findall(ONE, s))} single loads left', file=sys.stderr)
    return s

def convert(src, name):
    i = src.index('void main()'); return HEAD.format(src=name) + body(src[i + len('void main()'):])

if __name__ == '__main__':
    src = open(sys.argv[1]).read(); i = src.index('void main()')
    b = body(src[i + len('void main()'):])
    if os.environ.get('LOAD4') == '1': b = wide_loads(b)
    open(sys.argv[2], 'w').write(HEAD.format(src=sys.argv[1].rsplit('/', 1)[-1]) + b)
